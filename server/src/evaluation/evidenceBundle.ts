/**
 * Evidence bundle – self-contained HTML report for a run – Phase 6 (Should).
 */

export interface EvidenceInput {
  runId: string;
  task: string;
  status: string;
  provider?: string;
  model?: string;
  totalAttempts?: number;
  finalOutput?: string;
  finalError?: string;
  attempts?: Array<{
    attemptNumber: number;
    code?: string;
    success?: boolean;
    stdout?: string;
    stderr?: string;
    errorSummary?: string;
  }>;
  verdictSummary?: string;
  budget?: Record<string, unknown>;
  retrievedExperiences?: string[];
  finalDiff?: string;
}

export function buildEvidenceHtml(input: EvidenceInput): string {
  const esc = (s: string) =>
    String(s || "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");

  const attemptsHtml = (input.attempts || [])
    .map(
      (a) => `
    <section class="attempt">
      <h3>Attempt ${a.attemptNumber} — ${a.success ? "ok" : "fail"}</h3>
      ${a.errorSummary ? `<p class="err">${esc(a.errorSummary)}</p>` : ""}
      <pre>${esc(a.code || "")}</pre>
      <h4>stdout</h4><pre>${esc(a.stdout || "")}</pre>
      <h4>stderr</h4><pre>${esc(a.stderr || "")}</pre>
    </section>`
    )
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<title>CodeForge evidence — ${esc(input.runId)}</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 900px; margin: 2rem auto; padding: 0 1rem; color: #111; }
  h1 { font-size: 1.4rem; }
  .meta { color: #555; font-size: 0.9rem; }
  pre { background: #f6f8fa; padding: 12px; overflow: auto; border-radius: 8px; font-size: 12px; }
  .err { color: #b91c1c; }
  .badge { display: inline-block; padding: 2px 8px; border-radius: 999px; background: #ecfdf5; }
  .badge.fail { background: #fef2f2; }
</style>
</head>
<body>
  <h1>CodeForge evidence bundle</h1>
  <p class="meta">
    Run <code>${esc(input.runId)}</code> ·
    <span class="badge ${input.status === "success" || input.status === "completed" ? "" : "fail"}">${esc(input.status)}</span>
    ${input.provider ? `· ${esc(input.provider)}` : ""}
    ${input.model ? `· ${esc(input.model)}` : ""}
  </p>
  <h2>Task</h2>
  <pre>${esc(input.task)}</pre>
  ${input.verdictSummary ? `<h2>Verdict</h2><p>${esc(input.verdictSummary)}</p>` : ""}
  ${input.finalOutput ? `<h2>Final output</h2><pre>${esc(input.finalOutput)}</pre>` : ""}
  ${input.finalError ? `<h2>Final error</h2><p class="err">${esc(input.finalError)}</p>` : ""}
  ${input.finalDiff ? `<h2>Diff</h2><pre>${esc(input.finalDiff)}</pre>` : ""}
  ${
    input.retrievedExperiences?.length
      ? `<h2>Retrieved experiences</h2><ul>${input.retrievedExperiences.map((e) => `<li>${esc(e)}</li>`).join("")}</ul>`
      : ""
  }
  <h2>Attempts</h2>
  ${attemptsHtml || "<p>None</p>"}
  <footer class="meta">Generated by CodeForge Evolution · do not claim numbers not in committed results</footer>
</body>
</html>`;
}
